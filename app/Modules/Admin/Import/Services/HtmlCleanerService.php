<?php

namespace App\Modules\Admin\Import\Services;

class HtmlCleanerService
{
    public function clean(string $html): string
    {
        if (trim($html) === '') {
            return '';
        }

        /*
        |--------------------------------------------------------------------------
        | Normalize Line Breaks
        |--------------------------------------------------------------------------
        */

        $html = str_replace(
            ["\r\n", "\r"],
            "\n",
            $html
        );

        /*
        |--------------------------------------------------------------------------
        | Remove UTF-8 BOM
        |--------------------------------------------------------------------------
        */

        $html = preg_replace('/^\xEF\xBB\xBF/', '', $html);

        /*
        |--------------------------------------------------------------------------
        | Normalize NBSP
        |--------------------------------------------------------------------------
        */

        $html = str_replace(
            [
                '&nbsp;',
                "\xC2\xA0",
            ],
            ' ',
            $html
        );

        /*
        |--------------------------------------------------------------------------
        | Remove Office Namespace Tags
        |--------------------------------------------------------------------------
        */

        $html = preg_replace(
            '/<\/?(o|w|v):[^>]*>/i',
            '',
            $html
        );

        /*
        |--------------------------------------------------------------------------
        | Remove Empty Paragraphs
        |--------------------------------------------------------------------------
        */

        $html = preg_replace(
            '/<p[^>]*>\s*<\/p>/i',
            '',
            $html
        );

        /*
        |--------------------------------------------------------------------------
        | Remove Empty Divs
        |--------------------------------------------------------------------------
        */

        $html = preg_replace(
            '/<div[^>]*>\s*<\/div>/i',
            '',
            $html
        );

        /*
        |--------------------------------------------------------------------------
        | Remove Empty Spans
        |--------------------------------------------------------------------------
        */

        $html = preg_replace(
            '/<span[^>]*>\s*<\/span>/i',
            '',
            $html
        );

        /*
        |--------------------------------------------------------------------------
        | Normalize BR
        |--------------------------------------------------------------------------
        */

        $html = preg_replace(
            '/<br\s*\/?>/i',
            '<br>',
            $html
        );

        /*
        |--------------------------------------------------------------------------
        | Preserve Block Separation
        |--------------------------------------------------------------------------
        */

        $html = preg_replace('/<\/p>/i', "</p>\n", $html);
        $html = preg_replace('/<\/div>/i', "</div>\n", $html);
        $html = preg_replace('/<\/table>/i', "</table>\n", $html);
        $html = preg_replace('/<\/figure>/i', "</figure>\n", $html);
        $html = preg_replace('/<\/ul>/i', "</ul>\n", $html);
        $html = preg_replace('/<\/ol>/i', "</ol>\n", $html);

        /*
        |--------------------------------------------------------------------------
        | Collapse Multiple Blank Lines
        |--------------------------------------------------------------------------
        */

        $html = preg_replace(
            "/\n{3,}/",
            "\n\n",
            $html
        );

        return trim($html);
    }
}