<?php

namespace App\Services\AI;

class HtmlToTextService
{
    public function clean(?string $html): string
    {
        /*
        |------------------------------------------------------------------
        | EMPTY
        |------------------------------------------------------------------
        */

        if (! $html) {
            return '';
        }

        /*
        |------------------------------------------------------------------
        | REMOVE SCRIPT TAGS
        |------------------------------------------------------------------
        */

        $html = preg_replace(

            '/<script\b[^>]*>(.*?)<\/script>/is',

            '',

            $html
        );

        /*
        |------------------------------------------------------------------
        | REMOVE STYLE TAGS
        |------------------------------------------------------------------
        */

        $html = preg_replace(

            '/<style\b[^>]*>(.*?)<\/style>/is',

            '',

            $html
        );

        /*
        |------------------------------------------------------------------
        | REMOVE HTML TAGS
        |------------------------------------------------------------------
        */

        $text = strip_tags($html);

        /*
        |------------------------------------------------------------------
        | HTML ENTITIES
        |------------------------------------------------------------------
        */

        $text = html_entity_decode(

            $text,

            ENT_QUOTES | ENT_HTML5,

            'UTF-8'
        );

        /*
        |------------------------------------------------------------------
        | REMOVE EXTRA SPACES
        |------------------------------------------------------------------
        */

        $text = preg_replace(
            '/\s+/',
            ' ',
            $text
        );

        /*
        |------------------------------------------------------------------
        | TRIM
        |------------------------------------------------------------------
        */

        return trim($text);
    }
}
